# iPad 820x1180 shots of the new Card Battle School effects: ex entrance, ⚡ attack, Weakness x2, prize grab
from playwright.sync_api import sync_playwright
BASE='http://localhost:8765/'; OUT='/workspace/site/screenshots/'
errors=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome')
    ctx=b.new_context(viewport={'width':820,'height':1180}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg=ctx.new_page()
    pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('console', lambda m: m.type=='error' and errors.append(m.text))
    pg.goto(BASE+'#/games'); pg.wait_for_selector('.fg-pick.green'); pg.wait_for_timeout(500)
    pg.evaluate("localStorage.setItem('fg.tcLevel','easy');localStorage.setItem('fg.tcTips','1')")
    pg.click('.fg-pick.green'); pg.wait_for_selector('[data-mode="play"]')
    pg.evaluate("FentonTCG._force({op:'water', hand:['me55-53','E:lightning','E:lightning','E:lightning','E:lightning']})")
    pg.click('[data-mode="play"]'); pg.wait_for_selector('.tc-team.lightning'); pg.wait_for_timeout(300)
    pg.click('.tc-team.lightning'); pg.wait_for_selector('.tc.play')
    # friend's Active becomes Greninja ex (Weakness: Lightning)
    pg.wait_for_function('!FentonTCG._state().busy', timeout=8000); pg.wait_for_timeout(600)
    pg.evaluate("""(()=>{const S=FentonTCG._state();S.op.active={u:9001,id:'me55-21',dmg:0,en:['water','water'],turnIn:0,under:[],restUntil:0};S.fx={};FentonTCG._paint();})()""")
    pg.wait_for_timeout(400)
    pg.click('[data-act="deck"]'); pg.wait_for_timeout(900)
    u=pg.evaluate("FentonTCG._state().me.hand.find(c=>c.id==='me55-53').u")
    pg.click(f'[data-act="hand:{u}"]'); pg.wait_for_timeout(200)
    if pg.evaluate("FentonTCG._state().sel!=null"):
        pg.click('[data-act="meactive"]')
    pg.wait_for_timeout(1000); pg.screenshot(path=OUT+'tcg_ex_entrance.png'); print('ex entrance shot')
    pg.wait_for_function('!FentonTCG._state().busy', timeout=8000); pg.wait_for_timeout(500)
    # attach one Energy by tapping (shows the orb), then top up for the demo
    e=pg.evaluate("FentonTCG._state().me.hand.find(c=>c.id==='E:lightning').u")
    pg.click(f'[data-act="hand:{e}"]'); pg.wait_for_timeout(200)
    mu=pg.evaluate("FentonTCG._state().me.active.u")
    pg.click(f'[data-act="mon:{mu}"]'); pg.wait_for_timeout(900)
    pg.evaluate("(()=>{const S=FentonTCG._state();S.me.active.en=['lightning','lightning','lightning'];S.me.active.turnIn=0;S.fx={};FentonTCG._paint();})()")
    pg.wait_for_timeout(500)
    print('state before attack', pg.evaluate("(()=>{const S=FentonTCG._state();return {turn:S.turn,need:S.need,msg:document.getElementById('tcMsg').innerText,calc:FentonTCG._calc(S.me.active,0,S.op.active,S.me)}})()"))
    pg.click('[data-act="atk:0"]')
    pg.wait_for_timeout(480); pg.screenshot(path=OUT+'tcg_attack_effect.png'); print('attack shot')
    pg.wait_for_timeout(350); pg.screenshot(path=OUT+'tcg_weakness_x2.png'); print('weakness shot')
    pg.wait_for_function("FentonTCG._state().need==='prize'", timeout=30000); pg.wait_for_timeout(600)
    pg.screenshot(path=OUT+'tcg_prize_ready.png')
    print('need', pg.evaluate("[FentonTCG._state().need,FentonTCG._state().needN,document.getElementById('tcMsg').innerText]"))
    pg.click('[data-act="prize:0"]'); pg.wait_for_timeout(350)
    pg.screenshot(path=OUT+'tcg_prize_grab.png'); print('prize shot')
    pg.wait_for_timeout(1500)
    if pg.evaluate("FentonTCG._state().need==='prize'"): pg.click('[data-act="prize:0"]'); pg.wait_for_timeout(1500)
    print('after', pg.evaluate("(()=>{const S=FentonTCG._state();return {prizes:S.me.prizes.length,need:S.need,whose:S.whose,over:S.over}})()"))
    # reduced motion quick check: no errors, entrance skipped quickly
    b.close()
print('errors:',errors)
